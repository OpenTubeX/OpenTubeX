import { mkdirSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { homeWidgetStrings, loadTranslator, locales, root } from './nativeTranslations.mjs'

// Android still resolves Hebrew and Indonesian through their legacy language codes.
const legacyLanguages = { he: 'iw', id: 'in' }

const languageVariants = Object.groupBy(locales, locale => locale.split('-')[0])

// Regions are kept only to tell apart variants of the same language, so a device set to
// German (Austria) also gets the de-DE strings.
export function resourceDirectory(locale) {
  if (locale === 'en-US') return 'values'
  const [language, region] = locale.split('-')
  const qualifier = region && languageVariants[language].length > 1 ? `-r${region}` : ''
  return `values-${legacyLanguages[language] ?? language}${qualifier}`
}

export function escapeAndroidString(value) {
  return value
    .replaceAll('\\', '\\\\')
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '\\"')
    .replaceAll('\'', '\\\'')
    .replace(/^([@?])/, '\\$1')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  for (const locale of locales) {
    const translate = loadTranslator(locale)
    const strings = Object.entries(homeWidgetStrings)
      .map(([name, key]) => `    <string name="${name}">${escapeAndroidString(translate('Home Widgets', key))}</string>`)
    const directory = new URL(`android/app/src/main/res/${resourceDirectory(locale)}/`, root)
    mkdirSync(directory, { recursive: true })
    writeFileSync(new URL('widget_strings.xml', directory), `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by _scripts/prepareAndroid.mjs from static/locales. -->\n<resources>\n${strings.join('\n')}\n</resources>\n`)
  }
}
