test('triage stays silent when a proposed answer lacks source evidence', async t => {
  const originalFetch = globalThis.fetch
  t.after(() => { globalThis.fetch = originalFetch })
  let calls = 0
  globalThis.fetch = async () => {
    calls++
    const output = calls === 1
      ? { labels: ['enhancement'], reply: 'answer', source: 'extra-features' }
      : { answer: 'OpenTubeX has a queue.', evidence: 'This claim is absent from the guide.' }
    return { ok: true, json: async () => ({
      status: 'completed',
      output: [{ content: [{ type: 'output_text', text: JSON.stringify(output) }] }]
    }) }
  }
  const issue = { title: 'Queue', body: '', comments: { nodes: [] } }
  const result = await assess(issue, { readSource: async () => '### Watch queue\nQueue videos from the menu.' })
  assert.equal(calls, 2)
  assert.equal(result.answer, null)
  assert.deepEqual(result.labels, ['enhancement'])
})
