test('triage retries a response that exhausted its output tokens', async t => {
  const originalFetch = globalThis.fetch
  t.after(() => { globalThis.fetch = originalFetch })
  const budgets = []
  const efforts = []
  globalThis.fetch = async (_, options) => {
    const request = JSON.parse(options.body)
    budgets.push(request.max_output_tokens)
    efforts.push(request.reasoning.effort)
    return {
      ok: true,
      json: async () => budgets.length === 1
        ? { status: 'incomplete', incomplete_details: { reason: 'max_output_tokens' } }
        : {
            status: 'completed',
            output: [{ content: [{ type: 'output_text', text: '{"labels":["bug"],"reply":"none","source":"none"}' }] }]
          }
    }
  }
  const issue = { title: 'Report', body: '', comments: { nodes: [] } }
  assert.deepEqual(await assess(issue), { labels: ['bug'], reply: 'none', source: 'none' })
  assert.deepEqual(budgets, [250, 1000])
  assert.deepEqual(efforts, ['low', 'low'])
})

test('triage answers an existing-feature request from verified documentation', async t => {
  const originalFetch = globalThis.fetch
  t.after(() => { globalThis.fetch = originalFetch })
  const requests = []
  globalThis.fetch = async (_, options) => {
    const request = JSON.parse(options.body)
    requests.push(request)
    const output = requests.length === 1
      ? { labels: ['enhancement'], reply: 'answer', source: 'extra-features' }
      : {
          answer: 'Open the video menu and choose Add to Queue. Manage the queue in the watch page side panel.',
          evidence: 'Queue videos from their three-dot menus, then manage and drag to reorder them in a side panel on the watch page.',
          supported: true
        }
    return { ok: true, json: async () => ({
      status: 'completed',
      output: [{ content: [{ type: 'output_text', text: JSON.stringify(output) }] }]
    }) }
  }
  const issue = {
    title: 'Queue Feature for videos and shorts',
    body: 'Having the ability to create a queue of videos to watch would be very useful.',
    comments: { nodes: [] }
  }
  const result = await assess(issue, {
    readSource: async () => '### Watch queue\n\nQueue videos from their three-dot menus, then manage and drag to reorder them in a side panel on the watch page.'
  })
  assert.equal(requests.length, 2)
  assert.equal(Object.hasOwn(requests[1], 'signal'), false)
  assert.equal(result.reply, 'answer')
  assert.deepEqual(result.labels, ['enhancement'])
  assert.match(result.answer, /Add to Queue/)
  assert.match(result.answer, /https:\/\/opentubex\.org\/extra-features\/#watch-queue/)
})

