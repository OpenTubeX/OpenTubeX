import assert from 'node:assert/strict'
import { chmodSync, existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import test from 'node:test'
import { checkOutYtDlpCookies } from '../../src/main/ytDlpCookieFile.js'

const HEADER = '# Netscape HTTP Cookie File\n'
const cookie = (name, value, expires = '4102444800') => `.youtube.com\tTRUE\t/\tTRUE\t${expires}\t${name}\t${value}\n`
/** Saves a cookie file the way yt-dlp does when it exits. */
const save = (path, ...cookies) => writeFileSync(path, `${HEADER}# This file is generated by yt-dlp.  Do not edit.\n\n${cookies.join('')}`)

test('concurrent yt-dlp processes keep the cookies each of them rotated', (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'opentubex-cookie-test-'))
  t.after(() => rmSync(directory, { recursive: true, force: true }))
  const shared = join(directory, 'cookies.txt')
  // A session cookie and an HttpOnly one, which yt-dlp saves without their markers.
  writeFileSync(shared, `${HEADER}${cookie('SID', 'session', '')}#HttpOnly_${cookie('SIDTS', 'first')}${cookie('PREF', 'old')}`)

  const first = checkOutYtDlpCookies(['--cookies', shared, 'https://www.youtube.com/watch?v=aaaaaaaaaaa'])
  const second = checkOutYtDlpCookies(['--cookies', shared, 'https://www.youtube.com/watch?v=bbbbbbbbbbb'])
  const firstCopy = first.args[1]
  assert.notEqual(firstCopy, shared)
  assert.notEqual(second.args[1], firstCopy)
  assert.equal(readFileSync(firstCopy, 'utf8'), readFileSync(shared, 'utf8'))

  // The first process rotates the session token, and the second, which started
  // with the old token and exits later, only changes a preference.
  save(firstCopy, cookie('SID', 'session', '0'), cookie('SIDTS', 'second'), cookie('PREF', 'old'))
  save(second.args[1], cookie('SID', 'session', '0'), cookie('SIDTS', 'first'), cookie('PREF', 'new'), cookie('VISITOR', 'added'))
  first.release()
  second.release()

  const merged = readFileSync(shared, 'utf8')
  assert.match(merged, /\tSIDTS\tsecond\n/)
  assert.match(merged, /\tPREF\tnew\n/)
  assert.match(merged, /\tVISITOR\tadded\n/)
  assert.match(merged, /\tSID\tsession\n/)
  assert.equal(existsSync(firstCopy), false)

  // A process stopped while saving leaves a partial file, which must not remove cookies,
  // even when it stopped after a complete row.
  const stopped = checkOutYtDlpCookies(['--cookies', shared])
  writeFileSync(stopped.args[1], `${HEADER}${cookie('SID', 'session')}`.slice(0, -4))
  stopped.release()
  const cutAtRow = checkOutYtDlpCookies(['--cookies', shared])
  save(cutAtRow.args[1], cookie('SID', 'session', '0'))
  cutAtRow.release()
  assert.equal(readFileSync(shared, 'utf8'), merged)
})

test('a cookie merge that cannot be written keeps the previous file', { skip: process.platform === 'win32' || process.getuid?.() === 0 }, (t) => {
  const directory = mkdtempSync(join(tmpdir(), 'opentubex-cookie-test-'))
  t.after(() => {
    chmodSync(directory, 0o700)
    rmSync(directory, { recursive: true, force: true })
  })
  const shared = join(directory, 'cookies.txt')
  const before = `${HEADER}${cookie('SID', 'session')}${cookie('SIDTS', 'first')}`
  writeFileSync(shared, before)
  const cookies = checkOutYtDlpCookies(['--cookies', shared])
  save(cookies.args[1], cookie('SID', 'session'), cookie('SIDTS', 'second'))
  // Like a full disk, the folder has no room for the replacement.
  chmodSync(directory, 0o500)
  cookies.release()
  assert.equal(readFileSync(shared, 'utf8'), before)
})
