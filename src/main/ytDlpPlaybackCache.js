import { app } from 'electron'
import { Buffer } from 'node:buffer'
import { createHash } from 'node:crypto'
import { mkdir, readdir, readFile, rm } from 'node:fs/promises'
import { join } from 'node:path'

import { settings } from '../datastores/handlers/base'
import {
  DEFAULT_YT_DLP_PLAYBACK_CACHE_MAX_ENTRY_SIZE_MB,
  normalizeYtDlpPlaybackCacheMaxEntrySize
} from '../ytDlpPlaybackCacheSettings'
import { createSerialQueue } from './serialQueue'
import { TabManager } from './tabs/TabManager'
import { isTrustedSender } from './ipc'
import { writeFileAtomic } from './writeFileAtomic'

// Each source is stored in its own file, next to an index of them. Earlier
// versions kept every source in one file, held in memory and rewritten for
// each change, although sources can be several megabytes.
const CACHE_DIRECTORY = 'yt-dlp-playback-cache'
const INDEX_FILENAME = 'index.json'
const LEGACY_CACHE_FILENAME = 'yt-dlp-playback-cache.json'
const MAX_ENTRIES = 50
const EXPIRY_MARGIN_MS = 2 * 60 * 1000
const BYTES_PER_MEGABYTE = 1_000_000
// Sources can be up to 16 MB each, so the count alone does not bound the disk use.
const MAX_TOTAL_BYTES = 200 * BYTES_PER_MEGABYTE
const MAX_CACHE_KEY_LENGTH = 20_000
const VIDEO_ID_REGEX = /^[\w-]{11}$/
const CACHE_KEY_HASH_REGEX = /^[a-f\d]{64}$/

/**
 * @typedef {object} YtDlpPlaybackCacheEntry
 * @property {string} videoId
 * @property {string} cacheKeyHash
 * @property {number} expiryTime
 * @property {object} source
 */

/**
 * @typedef {object} YtDlpPlaybackCacheRecord
 * @property {string} videoId
 * @property {string} cacheKeyHash
 * @property {number} expiryTime
 * @property {number} size serialized length of the entry's file in bytes
 */

/**
 * The stored entries, least recently stored first.
 * @type {Map<string, YtDlpPlaybackCacheRecord>}
 */
const records = new Map()
let loadPromise = null
const enqueueWrite = createSerialQueue()
/**
 * Entry files still being written, which reads wait for.
 * @type {Map<string, Promise<void>>}
 */
const pendingEntryWrites = new Map()
let pendingIndexWrite = null
let cacheEnabled = true
let maxEntryLength = DEFAULT_YT_DLP_PLAYBACK_CACHE_MAX_ENTRY_SIZE_MB * BYTES_PER_MEGABYTE

function cacheDirectory() {
  return join(app.getPath('userData'), CACHE_DIRECTORY)
}

function entryPath(videoId) {
  return join(cacheDirectory(), `${videoId}.json`)
}

function hashCacheKey(cacheKey) {
  return createHash('sha256').update(cacheKey).digest('hex')
}

function isValidCacheKey(cacheKey) {
  return typeof cacheKey === 'string' && cacheKey.length <= MAX_CACHE_KEY_LENGTH
}

function isHttpsUrl(value) {
  if (typeof value !== 'string') return false

  try {
    return new URL(value).protocol === 'https:'
  } catch {
    return false
  }
}

function isValidCaption(caption) {
  return caption !== null &&
    typeof caption === 'object' &&
    isHttpsUrl(caption.url) &&
    typeof caption.language === 'string' &&
    caption.language.length > 0 &&
    typeof caption.label === 'string' &&
    caption.label.length > 0 &&
    caption.mimeType === 'text/vtt' &&
    (caption.id === undefined || typeof caption.id === 'string') &&
    (caption.translationName === undefined || typeof caption.translationName === 'string') &&
    (caption.originalLanguage === undefined || typeof caption.originalLanguage === 'string') &&
    (caption.isAutoGenerated === undefined || typeof caption.isAutoGenerated === 'boolean')
}

/**
 * @param {object} entry
 * @param {number} size serialized length in bytes
 */
function isValidEntry(entry, size) {
  if (entry === null || typeof entry !== 'object') return false

  const source = entry.source
  const legacyFormats = source?.legacyFormats
  const hasDashManifest = source?.manifestMimeType === 'application/dash+xml' &&
    typeof source.manifestSrc === 'string' &&
    source.manifestSrc.startsWith('data:application/dash+xml;')
  const hasHlsManifest = source?.manifestMimeType === 'application/x-mpegurl' &&
    isHttpsUrl(source.manifestSrc)
  const hasLegacyFormatsOnly = source?.manifestMimeType === 'application/dash+xml' &&
    source.manifestSrc === null &&
    Array.isArray(legacyFormats) &&
    legacyFormats.length > 0 &&
    legacyFormats.every(format => isHttpsUrl(format?.url))
  const hasValidCaptions = (source?.captions === undefined || (
    Array.isArray(source.captions) && source.captions.every(isValidCaption)
  )) && (source?.captionTranslations === undefined || (
    Array.isArray(source.captionTranslations) && source.captionTranslations.every(isValidCaption)
  ))

  return VIDEO_ID_REGEX.test(entry.videoId) &&
    CACHE_KEY_HASH_REGEX.test(entry.cacheKeyHash) &&
    Number.isFinite(entry.expiryTime) &&
    source !== null &&
    typeof source === 'object' &&
    source.isLive === false &&
    (hasDashManifest || hasHlsManifest || hasLegacyFormatsOnly) &&
    Array.isArray(legacyFormats) &&
    hasValidCaptions &&
    (source.storyboardSrc == null || (
      typeof source.storyboardSrc === 'string' &&
      source.storyboardSrc.startsWith('data:text/vtt;')
    )) &&
    (source.duration == null || (Number.isFinite(source.duration) && source.duration > 0)) &&
    (source.subtitlesIncluded === undefined || typeof source.subtitlesIncluded === 'boolean') &&
    (source.vrProjection === undefined || source.vrProjection === null || (
      hasHlsManifest && source.vrProjection === 'EQUIRECTANGULAR'
    )) &&
    (source.title === null || typeof source.title === 'string') &&
    size <= maxEntryLength
}

/**
 * @param {unknown} record
 * @returns {record is YtDlpPlaybackCacheRecord}
 */
function isValidRecord(record) {
  return record !== null &&
    typeof record === 'object' &&
    VIDEO_ID_REGEX.test(record.videoId) &&
    CACHE_KEY_HASH_REGEX.test(record.cacheKeyHash) &&
    Number.isFinite(record.expiryTime) &&
    Number.isInteger(record.size) &&
    record.size > 0
}

/**
 * @param {YtDlpPlaybackCacheRecord} record
 * @param {number} [now]
 */
function isUsable(record, now = Date.now()) {
  return now < record.expiryTime - EXPIRY_MARGIN_MS && record.size <= maxEntryLength
}

async function loadEntries() {
  if (loadPromise === null) {
    loadPromise = (async () => {
      try {
        const stored = JSON.parse(await readFile(join(cacheDirectory(), INDEX_FILENAME), 'utf8'))
        if (Array.isArray(stored)) {
          const now = Date.now()
          for (const record of stored.slice(-MAX_ENTRIES)) {
            if (isValidRecord(record) && isUsable(record, now)) {
              const { videoId, cacheKeyHash, expiryTime, size } = record
              records.set(videoId, { videoId, cacheKeyHash, expiryTime, size })
            }
          }
        }
      } catch (error) {
        if (error.code !== 'ENOENT') {
          console.warn('Could not load the yt-dlp playback cache', error)
        }
      }
      enqueueWrite(removeUnindexedFiles).catch(error => {
        console.warn('Could not clean up the yt-dlp playback cache', error)
      })
    })()
  }
  await loadPromise
}

/** Removes the earlier single-file cache, and entries a crash left out of the index. */
async function removeUnindexedFiles() {
  const userData = app.getPath('userData')
  await Promise.all([LEGACY_CACHE_FILENAME, `${LEGACY_CACHE_FILENAME}.tmp`].map(name => rm(join(userData, name), { force: true })))
  let names
  try {
    names = await readdir(cacheDirectory())
  } catch (error) {
    if (error.code === 'ENOENT') return
    throw error
  }
  await Promise.all(names
    .filter(name => name !== INDEX_FILENAME && !(name.endsWith('.json') && records.has(name.slice(0, -5))))
    .map(name => rm(join(cacheDirectory(), name), { force: true })))
}

function saveIndex() {
  // A burst of changes (for example preloading the upcoming playlist videos)
  // shares one write that snapshots the latest index.
  if (pendingIndexWrite === null) {
    const write = enqueueWrite(async () => {
      if (pendingIndexWrite === write) pendingIndexWrite = null
      await mkdir(cacheDirectory(), { recursive: true })
      return writeFileAtomic(join(cacheDirectory(), INDEX_FILENAME), JSON.stringify([...records.values()]))
    })
    pendingIndexWrite = write
  }
  return pendingIndexWrite
}

/**
 * @param {string[]} videoIds entries already removed from the index
 */
function removeEntryFiles(videoIds) {
  if (videoIds.length === 0) return Promise.resolve()
  // A write queued meanwhile can store the video again, and its file must stay.
  return enqueueWrite(() => Promise.all(videoIds
    .filter(videoId => !records.has(videoId))
    .map(videoId => rm(entryPath(videoId), { force: true }))))
}

/**
 * @param {YtDlpPlaybackCacheRecord} record
 */
async function deleteRecord(record) {
  if (records.get(record.videoId) !== record) return
  records.delete(record.videoId)
  await Promise.all([removeEntryFiles([record.videoId]), saveIndex()])
}

export async function handleYtDlpPlaybackCacheGet(event, videoId, cacheKey) {
  if (
    !isTrustedSender(event) ||
    !VIDEO_ID_REGEX.test(videoId) ||
    !isValidCacheKey(cacheKey)
  ) return null
  await settingsApplied.catch(() => {})
  if (!cacheEnabled) return null

  await loadEntries()
  if (!cacheEnabled) return null
  const record = records.get(videoId)
  if (record === undefined) return null

  if (record.cacheKeyHash !== hashCacheKey(cacheKey) || !isUsable(record)) {
    await deleteRecord(record)
    return null
  }

  // The index lists a new entry before its file is written.
  await pendingEntryWrites.get(videoId)?.catch(() => {})
  if (records.get(videoId) !== record) return null

  let text
  try {
    text = await readFile(entryPath(videoId), 'utf8')
  } catch {
    await deleteRecord(record)
    return null
  }
  // A write of a newer source for the video is still in progress.
  if (records.get(videoId) !== record) return null

  let entry = null
  try {
    entry = JSON.parse(text)
  } catch {}
  if (
    entry?.videoId !== videoId ||
    entry.cacheKeyHash !== record.cacheKeyHash ||
    !isValidEntry(entry, Buffer.byteLength(text, 'utf8'))
  ) {
    await deleteRecord(record)
    return null
  }
  if (Date.now() >= entry.expiryTime - EXPIRY_MARGIN_MS) return null

  return { expiryTime: entry.expiryTime, source: entry.source }
}

export async function handleYtDlpPlaybackCacheSet(event, videoId, cacheKey, expiryTime, source) {
  if (
    !isTrustedSender(event) ||
    !VIDEO_ID_REGEX.test(videoId) ||
    !isValidCacheKey(cacheKey)
  ) return false
  await settingsApplied.catch(() => {})
  if (!cacheEnabled) return false

  const entry = {
    videoId,
    cacheKeyHash: hashCacheKey(cacheKey),
    expiryTime,
    source: source === null || typeof source !== 'object'
      ? source
      : {
          manifestSrc: source.manifestSrc,
          manifestMimeType: source.manifestMimeType,
          legacyFormats: source.legacyFormats,
          captions: source.captions,
          captionTranslations: source.captionTranslations,
          subtitlesIncluded: source.subtitlesIncluded,
          title: source.title,
          storyboardSrc: source.storyboardSrc,
          duration: source.duration,
          isLive: source.isLive,
          vrProjection: source.vrProjection,
          version: source.version
        }
  }

  // Serialized once, to measure the entry and to write its file.
  let json
  try {
    json = JSON.stringify(entry)
  } catch {
    return false
  }
  const size = Buffer.byteLength(json, 'utf8')
  if (!isValidEntry(entry, size)) return false
  if (Date.now() >= entry.expiryTime - EXPIRY_MARGIN_MS) return false

  await loadEntries()
  if (!cacheEnabled || !isValidEntry(entry, size)) return false
  records.delete(videoId)
  // Expired entries are otherwise only dropped when read, so they would stay
  // on disk until 50 newer entries push them out.
  const evicted = []
  let totalSize = size
  const now = Date.now()
  for (const record of records.values()) {
    if (isUsable(record, now)) {
      totalSize += record.size
    } else {
      records.delete(record.videoId)
      evicted.push(record.videoId)
    }
  }
  const openVideoIds = TabManager.getOpenVideoIds()
  while (records.size > 0 && (records.size >= MAX_ENTRIES || totalSize > MAX_TOTAL_BYTES)) {
    const evictedId = Array.from(records.keys()).find(id => !openVideoIds.has(id)) ?? records.keys().next().value
    totalSize -= records.get(evictedId).size
    records.delete(evictedId)
    evicted.push(evictedId)
  }
  const record = { videoId, cacheKeyHash: entry.cacheKeyHash, expiryTime: entry.expiryTime, size }
  records.set(videoId, record)

  const write = enqueueWrite(async () => {
    await mkdir(cacheDirectory(), { recursive: true })
    await writeFileAtomic(entryPath(videoId), json)
  })
  pendingEntryWrites.set(videoId, write)
  try {
    await write
  } catch (error) {
    // Without its file, the entry must not stay in the index.
    if (records.get(videoId) === record) records.delete(videoId)
    await Promise.all([removeEntryFiles(evicted), saveIndex()])
    throw error
  } finally {
    if (pendingEntryWrites.get(videoId) === write) pendingEntryWrites.delete(videoId)
  }
  await Promise.all([removeEntryFiles(evicted), saveIndex()])
  return true
}

export async function handleYtDlpPlaybackCacheDelete(event, videoId) {
  if (!isTrustedSender(event) || !VIDEO_ID_REGEX.test(videoId)) return false

  await loadEntries()
  const record = records.get(videoId)
  if (record !== undefined) await deleteRecord(record)
  return true
}

export async function handleYtDlpPlaybackCacheClear(event) {
  if (!isTrustedSender(event)) return false

  await clearYtDlpPlaybackCache()
  return true
}

export async function clearYtDlpPlaybackCache() {
  await loadEntries()
  records.clear()
  const userData = app.getPath('userData')
  const clear = enqueueWrite(() => Promise.all([
    rm(cacheDirectory(), { recursive: true, force: true }),
    rm(join(userData, LEGACY_CACHE_FILENAME), { force: true }),
    rm(join(userData, `${LEGACY_CACHE_FILENAME}.tmp`), { force: true })
  ]))
  // A save requested from now on must run after the clear, not share a
  // write that was queued before it.
  pendingIndexWrite = null
  await clear
}

// Startup applies the settings without waiting, so the handlers wait for them
// instead of serving entries the user disabled.
let settingsApplied = Promise.resolve()

export function applyYtDlpPlaybackCacheSettings() {
  settingsApplied = applySettings()
  return settingsApplied
}

async function applySettings() {
  const maxEntrySizeSetting = await settings._findOne('ytDlpPlaybackCacheMaxEntrySize')
  const maxEntrySize = normalizeYtDlpPlaybackCacheMaxEntrySize(maxEntrySizeSetting?.value)

  cacheEnabled = maxEntrySize > 0
  maxEntryLength = maxEntrySize * BYTES_PER_MEGABYTE

  await loadEntries()
  if (!cacheEnabled) {
    await clearYtDlpPlaybackCache()
    return
  }

  const oversized = [...records.values()].filter(record => record.size > maxEntryLength)
  if (oversized.length === 0) return
  for (const record of oversized) records.delete(record.videoId)
  await Promise.all([removeEntryFiles(oversized.map(record => record.videoId)), saveIndex()])
}
